-- A null financial snapshot means historical/unknown, never a backfilled assertion of refund zero.
CREATE TABLE IF NOT EXISTS payment_financial_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
    snapshot_key VARCHAR(64) NOT NULL UNIQUE,
    status VARCHAR(30) NOT NULL,
    transaction_amount NUMERIC(12,2) NOT NULL,
    refunded_amount NUMERIC(12,2) NOT NULL,
    provider_updated_at TIMESTAMP WITH TIME ZONE,
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_payment_financial_events_payment ON payment_financial_events(payment_id,id);
