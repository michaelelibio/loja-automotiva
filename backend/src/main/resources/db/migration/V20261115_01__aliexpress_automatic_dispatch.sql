ALTER TABLE order_fulfillments ADD COLUMN IF NOT EXISTS dispatch_quote JSONB;
ALTER TABLE order_fulfillments ADD COLUMN IF NOT EXISTS dispatch_check_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE order_fulfillments ADD COLUMN IF NOT EXISTS dispatch_next_check_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE order_fulfillments ADD COLUMN IF NOT EXISTS dispatch_payload_hash VARCHAR(64);
ALTER TABLE order_fulfillments ADD COLUMN IF NOT EXISTS supplier_costs JSONB;
ALTER TABLE order_fulfillments ADD COLUMN IF NOT EXISTS dispatch_manual_hold BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE order_fulfillments ADD COLUMN IF NOT EXISTS dispatch_review_context VARCHAR(64);
ALTER TABLE order_fulfillments ADD COLUMN IF NOT EXISTS dispatch_review_at TIMESTAMP WITH TIME ZONE;
CREATE TABLE IF NOT EXISTS aliexpress_dispatch_records (
    order_id BIGINT PRIMARY KEY REFERENCES orders(id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL,
    automatic_eligible BOOLEAN NOT NULL DEFAULT TRUE,
    next_check_at TIMESTAMP WITH TIME ZONE,
    state JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_aliexpress_secondary_pending ON aliexpress_dispatch_records(status,next_check_at);
CREATE TABLE IF NOT EXISTS aliexpress_recipient_admin_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    actor_id VARCHAR(120) NOT NULL,
    action VARCHAR(40) NOT NULL,
    previous_context VARCHAR(64) NOT NULL,
    current_context VARCHAR(64) NOT NULL,
    attempt_count INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_aliexpress_recipient_audit_order ON aliexpress_recipient_admin_audits(order_id,id);
CREATE INDEX IF NOT EXISTS idx_aliexpress_dispatch_pending ON order_fulfillments (status, dispatch_next_check_at, order_id)
    WHERE provider = 'ALIEXPRESS' AND attempt_count = 0;
